#pragma once

#include "core/templates/safe_refcount.h"

class GDScript;

// Target policy for an isolated export compiler process. Never execute project
// static initializers while constructing an exported script graph.
class GDScriptCompilationContext {
	static SafeNumeric<uint64_t> source_pipeline_entries;
	static SafeNumeric<uint64_t> initialization_sequence;

public:
	static bool is_compile_only();
	static bool is_debug_compilation();
	static void record_initialization_order(GDScript *p_script);
	static void record_source_pipeline_entry();
	static uint64_t get_source_pipeline_entries();
};
